#!/usr/bin/env python3
"""Stream a complete original ZIP plus a validated partial workspace overlay.

No extraction is required. Missing workspace baseline files are retained from
the original archive. The only original file allowed to change is README.md;
all historical scientific evidence, paper/ and artifact/src/ stay byte-exact.

plan  : inspect the complete intended content without producing the release.
build : stream, fully CRC/SHA-verify, then publish a new ZIP without overwrite.
verify: independently compare an existing release with the original archive.

DELIVERY_INTEGRITY.json is inside the ZIP and excludes its own hash. A separate
receipt binds the final ZIP hash and actual verification, avoiding recursion.
"""
from __future__ import annotations

import argparse
import copy
from datetime import date, datetime, timezone
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import stat
import sys
import tempfile
import zipfile

MANIFEST = "DELIVERY_INTEGRITY.json"
SCHEMA = "repairseal-complete-overlay-integrity-v1"
ALLOWED_ORIGINAL_CHANGES = frozenset({"README.md"})
CHUNK = 1024 * 1024
IGNORED_DIRECTORIES = frozenset({"__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache",
                                 ".git", ".venv", "node_modules", "__MACOSX", "temp-build", "tmp-build"})
LATEX_AUX_SUFFIXES = (".aux", ".out", ".blg", ".toc", ".lof", ".lot", ".nav", ".snm",
                      ".vrb", ".fls", ".fdb_latexmk", ".synctex.gz")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=True, separators=(",", ":"), allow_nan=False).encode()


def pretty(value):
    return (json.dumps(value, sort_keys=True, ensure_ascii=True, indent=2, allow_nan=False) + "\n").encode()


def decode_json(raw):
    def pairs(entries):
        result = {}
        for key, value in entries:
            require(key not in result, "duplicate JSON key: " + key)
            result[key] = value
        return result
    return json.loads(raw, object_pairs_hook=pairs,
                      parse_constant=lambda value: (_ for _ in ()).throw(ValueError(value)))


def hash_stream(source, target=None):
    sha = hashlib.sha256(); size = 0
    for block in iter(lambda: source.read(CHUNK), b""):
        sha.update(block); size += len(block)
        if target is not None: target.write(block)
    return sha.hexdigest(), size


def hash_file(path):
    with path.open("rb") as stream:
        return hash_stream(stream)[0]


def row(path, digest, size, directory=False):
    return {"path": path, "sha256": digest, "bytes": size, "directory": directory}


def inventory_digest(rows):
    sha = hashlib.sha256()
    for item in sorted(rows, key=lambda item: item["path"]):
        sha.update(canonical(item)); sha.update(b"\n")
    return sha.hexdigest()


def archive_index(archive):
    infos = archive.infolist()
    require(bool(infos), "empty original archive")
    prefix = None; result = {}
    for info in infos:
        name = info.filename
        pure = PurePosixPath(name)
        require(not pure.is_absolute() and ".." not in pure.parts and "\\" not in name
                and len(pure.parts) >= 2 and name == pure.as_posix() + ("/" if info.is_dir() else ""),
                "noncanonical or unsafe archive member: " + name)
        require(not stat.S_ISLNK(info.external_attr >> 16), "archive symlinks are not admitted")
        if prefix is None: prefix = pure.parts[0]
        require(pure.parts[0] == prefix, "archive must have one project prefix")
        relative = "/".join(pure.parts[1:]) + ("/" if info.is_dir() else "")
        require(relative not in result, "duplicate archive member: " + relative)
        result[relative] = info
    return prefix, result


def exclusion_reason(relative):
    if relative.as_posix() == MANIFEST:
        return "integrity manifest generated by packager; self hash excluded"
    if any(part in IGNORED_DIRECTORIES or part.startswith(("verify-negative-", "weak-order-native-"))
           for part in relative.parts[:-1]):
        return "cache or transient build directory"
    if relative.name in {".DS_Store", "missfont.log"} or relative.suffix in {".pyc", ".pyo"}:
        return "cache or transient output"
    if (relative.parts[0] in {"paper", "paper-revised"} and "build-record" not in relative.parts
            and relative.name.endswith(LATEX_AUX_SUFFIXES)):
        return "LaTeX auxiliary output; PDFs, bibliography and log receipts are retained"
    if relative.name.endswith(("~", ".swp", ".swo", ".tmp")):
        return "editor or temporary output"
    return None


def workspace_files(project, original_paths):
    files = {}; ignored = []
    for path in sorted(project.rglob("*")):
        relative = path.relative_to(project)
        rel = relative.as_posix()
        if rel == MANIFEST:
            # A previously generated manifest must not perturb its own next
            # content, including through an ignored-file listing.
            continue
        if path.is_dir() and not path.is_symlink():
            continue
        # An exclusion can never remove an original archive member. For an
        # original local file, compare bytes even if a generic cache rule fits.
        reason = None if rel in original_paths else exclusion_reason(relative)
        if reason is not None:
            ignored.append({"path": rel, "reason": reason}); continue
        require(not path.is_symlink(), "workspace symlink is not a release file: " + rel)
        require(path.is_file(), "nonregular workspace object: " + rel)
        files[rel] = path
    return files, ignored


def inspect(original, project, release_date):
    require(original.is_file() and project.is_dir(), "original ZIP and project directory are required")
    require(date.fromisoformat(release_date).isoformat() == release_date, "ISO release date")
    original_hash = hash_file(original)
    original_rows = []; unchanged = []; changed = []; final = {}; local_hashes = {}
    with zipfile.ZipFile(original) as source:
        prefix, originals = archive_index(source)
        require(MANIFEST not in originals, "reserved integrity manifest already exists in baseline")
        local, ignored = workspace_files(project, originals)
        for rel, info in sorted(originals.items()):
            with source.open(info) as stream:
                old_hash, old_size = hash_stream(stream)
            require(old_size == info.file_size, "incomplete original archive member: " + rel)
            old_row = row(rel, old_hash, old_size, info.is_dir())
            original_rows.append(old_row)
            if rel in local:
                with local[rel].open("rb") as stream:
                    new_hash, new_size = hash_stream(stream)
                local_hashes[rel] = (new_hash, new_size)
                if (new_hash, new_size) != (old_hash, old_size):
                    require(rel in ALLOWED_ORIGINAL_CHANGES,
                            "protected original changed; restore exact baseline bytes: " + rel)
                    changed.append({"path": rel, "original_sha256": old_hash, "original_bytes": old_size,
                                    "release_sha256": new_hash, "release_bytes": new_size})
                    final[rel] = row(rel, new_hash, new_size)
                    continue
            unchanged.append(old_row); final[rel] = old_row
        added = []
        for rel, path in sorted(local.items()):
            if rel in originals: continue
            with path.open("rb") as stream:
                digest, size = hash_stream(stream)
            added.append(row(rel, digest, size)); final[rel] = added[-1]
            local_hashes[rel] = (digest, size)
        manifest = {
            "schema": SCHEMA, "release_date": release_date, "project_prefix": prefix,
            "original_archive": {"filename": original.name, "bytes": original.stat().st_size,
                                 "sha256": original_hash, "members": len(originals),
                                 "uncompressed_bytes": sum(r["bytes"] for r in original_rows),
                                 "inventory_sha256": inventory_digest(original_rows)},
            "original_members_all_retained": True,
            "allowed_original_changes": sorted(ALLOWED_ORIGINAL_CHANGES),
            "unchanged_original_members": len(unchanged),
            "unchanged_original_inventory_sha256": inventory_digest(unchanged),
            "changed_originals": changed,
            "new_members": len(added), "new_files": added,
            "new_inventory_sha256": inventory_digest(added),
            "content_members_excluding_manifest": len(final),
            "archive_members_including_manifest": len(final) + 1,
            "content_inventory_sha256": inventory_digest(final.values()),
            "content_uncompressed_bytes_excluding_manifest": sum(r["bytes"] for r in final.values()),
            "inventory_encoding": "SHA256 of path-sorted compact canonical JSON rows plus LF; row fields are bytes,directory,path,sha256",
            "preservation_scope": "Every original member is retained. Every original payload except explicitly recorded README.md changes is byte-identical, including all historical paper/, artifact/src/, experiments, data, results and receipts. Missing local baseline files come directly from the original ZIP.",
            "verification_scope": "After writing, every final member is fully read through zipfile (CRC checked) and SHA256 checked; original-member preservation, new-member closure, all inventory digests and the internal manifest are independently verified. Actual results and the final outer-ZIP SHA256 are in the adjacent .receipt.json file.",
            "self_reference_exclusions": [MANIFEST, "outer ZIP and adjacent receipt"],
            "ignored_new_workspace_items": ignored,
        }
    return manifest, final, local, originals


def new_info(name, release_date):
    value = date.fromisoformat(release_date)
    info = zipfile.ZipInfo(name, (value.year, value.month, value.day, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    info._compresslevel = 6
    info.create_system = 3
    info.external_attr = (stat.S_IFREG | (0o755 if name.endswith(".sh") else 0o644)) << 16
    return info


def validate(original, release):
    """Full independent CRC+SHA read. Does not trust manifest allowlists."""
    original_hash = hash_file(original)
    with zipfile.ZipFile(original) as source, zipfile.ZipFile(release) as target:
        prefix, originals = archive_index(source)
        target_prefix, outputs = archive_index(target)
        require(target_prefix == prefix and MANIFEST in outputs, "release prefix/manifest")
        manifest_bytes = target.read(outputs[MANIFEST])
        manifest = decode_json(manifest_bytes)
        require(manifest["schema"] == SCHEMA and manifest["project_prefix"] == prefix, "integrity schema")
        require(manifest["allowed_original_changes"] == sorted(ALLOWED_ORIGINAL_CHANGES), "untrusted change permission")
        require(manifest["original_archive"]["sha256"] == original_hash
                and manifest["original_archive"]["bytes"] == original.stat().st_size, "original archive binding")
        final_rows = {}
        # Fully consuming each ZipExtFile performs its CRC32 check. Combining
        # that with SHA256 avoids a redundant second testzip() decompression.
        for rel, info in sorted(outputs.items()):
            if rel == MANIFEST: continue
            with target.open(info) as stream:
                digest, size = hash_stream(stream)
            require(size == info.file_size, "incomplete final member")
            final_rows[rel] = row(rel, digest, size, info.is_dir())
        changed = {r["path"]: r for r in manifest["changed_originals"]}
        require(len(changed) == len(manifest["changed_originals"]) and set(changed) <= ALLOWED_ORIGINAL_CHANGES,
                "duplicate or forbidden original change")
        original_rows = []; unchanged_rows = []
        for rel, info in sorted(originals.items()):
            require(rel in final_rows, "original member lost: " + rel)
            with source.open(info) as stream:
                digest, size = hash_stream(stream)
            old = row(rel, digest, size, info.is_dir()); original_rows.append(old)
            new = final_rows[rel]
            if rel in changed:
                expected = {"path": rel, "original_sha256": digest, "original_bytes": size,
                            "release_sha256": new["sha256"], "release_bytes": new["bytes"]}
                require(changed[rel] == expected and old != new, "changed-original identity")
            else:
                require(old == new, "protected original byte preservation failed: " + rel)
                unchanged_rows.append(old)
        new_rows = [final_rows[rel] for rel in sorted(set(final_rows) - set(originals))]
        require(manifest["new_files"] == new_rows, "new-member inventory closure")
        require(manifest["new_members"] == len(new_rows)
                and manifest["unchanged_original_members"] == len(unchanged_rows)
                and manifest["original_archive"]["members"] == len(originals)
                and manifest["content_members_excluding_manifest"] == len(final_rows)
                and manifest["archive_members_including_manifest"] == len(outputs), "member counts")
        require(manifest["original_members_all_retained"] is True, "baseline preservation assertion")
        require(manifest["original_archive"]["inventory_sha256"] == inventory_digest(original_rows)
                and manifest["original_archive"]["uncompressed_bytes"] == sum(r["bytes"] for r in original_rows)
                and manifest["unchanged_original_inventory_sha256"] == inventory_digest(unchanged_rows)
                and manifest["new_inventory_sha256"] == inventory_digest(new_rows)
                and manifest["content_inventory_sha256"] == inventory_digest(final_rows.values())
                and manifest["content_uncompressed_bytes_excluding_manifest"] == sum(r["bytes"] for r in final_rows.values()),
                "inventory digest or byte totals")
        receipt = {
            "schema": "repairseal-complete-overlay-receipt-v1", "status": "PASS",
            "verified_utc": datetime.now(timezone.utc).isoformat(),
            "archive": release.name, "archive_bytes": release.stat().st_size,
            "archive_sha256": hash_file(release), "original_archive_sha256": original_hash,
            "integrity_manifest_sha256": hashlib.sha256(manifest_bytes).hexdigest(),
            "crc_checked_members": len(outputs), "sha256_checked_content_members": len(final_rows),
            "original_members_retained": len(originals), "unchanged_original_members": len(unchanged_rows),
            "changed_original_paths": sorted(changed), "added_members_excluding_manifest": len(new_rows),
            "content_inventory_sha256": manifest["content_inventory_sha256"],
            "historical_paper_and_receiver_sources_byte_identical": True,
            "verification_method": "Fully read every final ZIP member through zipfile CRC validation; independently SHA256-compare every original payload against the original archive except README.md, and verify every declared changed/new payload and complete inventory closure. No omitted local baseline file is treated as deleted.",
        }
    return receipt, manifest_bytes


def build(original, project, output, release_date):
    require(not output.exists(), "refusing to overwrite final release: " + str(output))
    require(project != output and project not in output.parents, "release ZIP must be outside project tree")
    output.parent.mkdir(parents=True, exist_ok=True)
    receipt_path = output.with_name(output.name + ".receipt.json")
    require(not receipt_path.exists(), "refusing to overwrite release receipt")
    manifest, expected, local, _ = inspect(original, project, release_date)
    manifest_bytes = pretty(manifest)
    require(shutil.disk_usage(output.parent).free > original.stat().st_size + 64*1024*1024,
            "insufficient free space for streaming release; leave original archive untouched")
    fd, temporary_name = tempfile.mkstemp(prefix=".repairseal-building-", suffix=".zip", dir=output.parent)
    os.close(fd); temporary = Path(temporary_name)
    try:
        with zipfile.ZipFile(original) as source, zipfile.ZipFile(temporary, "w", compression=zipfile.ZIP_DEFLATED,
                                                              compresslevel=6, allowZip64=True) as target:
            prefix, originals = archive_index(source)
            target.comment = source.comment
            changed = {item["path"] for item in manifest["changed_originals"]}
            for rel, old_info in originals.items():
                info = copy.copy(old_info)
                with target.open(info, "w", force_zip64=True) as destination:
                    if rel in changed:
                        with local[rel].open("rb") as stream: digest, size = hash_stream(stream, destination)
                    else:
                        with source.open(old_info) as stream: digest, size = hash_stream(stream, destination)
                require((digest, size) == (expected[rel]["sha256"], expected[rel]["bytes"]),
                        "source changed during packaging: " + rel)
            for item in manifest["new_files"]:
                rel = item["path"]
                with local[rel].open("rb") as stream, target.open(new_info(prefix + "/" + rel, release_date), "w", force_zip64=True) as destination:
                    digest, size = hash_stream(stream, destination)
                require((digest, size) == (item["sha256"], item["bytes"]), "overlay changed during packaging: " + rel)
            target.writestr(new_info(prefix + "/" + MANIFEST, release_date), manifest_bytes)
        current_local, _ = workspace_files(project, originals)
        require(set(current_local) == set(local), "workspace file inventory changed during packaging")
        for rel, path in current_local.items():
            with path.open("rb") as stream: digest, size = hash_stream(stream)
            require((digest, size) == (expected[rel]["sha256"], expected[rel]["bytes"]),
                    "workspace file changed during packaging: " + rel)
        receipt, verified_manifest = validate(original, temporary)
        require(verified_manifest == manifest_bytes, "written manifest differs")
        # Atomic no-clobber publication. The temporary file and final file are
        # in the same directory/filesystem; link fails if another writer won.
        os.link(temporary, output)
        temporary.unlink()
        receipt["archive"] = output.name
        with receipt_path.open("xb") as stream: stream.write(pretty(receipt))
        (project / MANIFEST).write_bytes(manifest_bytes)
        return receipt
    finally:
        if temporary.exists(): temporary.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    for action in ("plan", "build"):
        command = sub.add_parser(action)
        command.add_argument("--original", type=Path, required=True)
        command.add_argument("--project", type=Path, required=True)
        command.add_argument("--release-date", default="2026-11-27")
        if action == "build": command.add_argument("--output", type=Path, required=True)
    check = sub.add_parser("verify")
    check.add_argument("--original", type=Path, required=True)
    check.add_argument("--archive", type=Path, required=True)
    args = parser.parse_args()
    if args.action == "plan":
        manifest, _, _, _ = inspect(args.original.resolve(), args.project.resolve(), args.release_date)
        result = {"status": "PLAN_ONLY_NO_ZIP_WRITTEN", "project_prefix": manifest["project_prefix"],
                  "original_members": manifest["original_archive"]["members"],
                  "original_archive_sha256": manifest["original_archive"]["sha256"],
                  "unchanged_original_members": manifest["unchanged_original_members"],
                  "changed_originals": manifest["changed_originals"],
                  "new_members": manifest["new_members"],
                  "archive_members_including_manifest": manifest["archive_members_including_manifest"],
                  "ignored_new_workspace_items": manifest["ignored_new_workspace_items"],
                  "content_inventory_sha256": manifest["content_inventory_sha256"]}
    elif args.action == "build":
        result = build(args.original.resolve(), args.project.resolve(), args.output.resolve(), args.release_date)
    else:
        result, _ = validate(args.original.resolve(), args.archive.resolve())
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
